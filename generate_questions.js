// HTMLから<b>タグの内容を抽出（キーワード候補）
function extractKeywords(html) {
  const bolds = [...html.matchAll(/<b>([^<]+)<\/b>/g)].map(m => m[1].trim()).filter(t => t.length > 1);
  const lis = [...html.matchAll(/<li>([^<]+)<\/li>/g)].map(m => m[1].trim()).filter(t => t.length > 5);
  return { bolds, lis };
}

