function buildQuestions() {
  const questions = [];
  const seen = new Set();
  
  // 既存問題を追加
  for (const q of existingQuestions) {
    const key = q.q.substring(0, 20);
    if (!seen.has(key)) {
      questions.push(q);
      seen.add(key);
    }
  }
  
  // テンプレートから追加
  for (const [tag, qs] of Object.entries(questionTemplates)) {
    let area = 'r';
    if (['都市計画法','建築基準法①','建築基準法②','国土利用計画法','農地法','宅地造成','その他法令'].includes(tag)) area = 'l';
    else if (['宅建業法①','宅建業法②','宅建業法③','宅建業法④','宅建業法⑤'].includes(tag)) area = 't';
    else if (['不動産取得税','印紙税'].includes(tag)) area = 'z';
    
    for (const q of qs) {
      const key = q.q.substring(0, 20);
      if (!seen.has(key)) {
        questions.push({...q, tag, area});
        seen.add(key);
      }
    }
  }
  
  return questions;
}

